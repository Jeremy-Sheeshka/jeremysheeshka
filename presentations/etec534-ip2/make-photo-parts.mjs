/**
 * make-photo-parts.mjs — writes photo-parts.include.html
 *
 * Every photograph in the deck is used from inside a drawing (so it can be
 * tilted, taped down, tipped with the scale, or clicked to enlarge), and Quarto
 * only embeds pictures it finds in <img> tags. So this puts each one into the
 * page once, as an SVG <symbol> with the file's bytes written into it, and the
 * slides refer to them with <use href="#ph-...">.
 *
 * render.sh runs this before Quarto. To add a photograph, add a line to PHOTOS.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

// name, file under img/, width, height (the picture's own size in pixels)
const PHOTOS = [
	["bottle", "cut-bottle.webp", 420, 737],
	["misnon", "cut-misnon.webp", 260, 498],
	["brush", "cut-brush.webp", 170, 514],
	["eraser", "cut-eraser.webp", 300, 304],
	["liquidpaper", "cut-liquidpaper.webp", 420, 370],
	["selectric", "cut-selectric.webp", 460, 278],
	["tape", "cut-tape.webp", 420, 249],
	["pen", "cut-pen.webp", 520, 184],
	["keys", "cut-keys.webp", 420, 195],
	["page", "correction-on-page-2008.jpg", 1040, 373],
	["ad", "papermate-marriage-2012.jpg", 900, 612],
	["drabble-detail", "drabble-1989-detail.jpg", 672, 630],
	["drabble-panel", "drabble-1989-panel1.jpg", 960, 1108],
];

const MIME = { webp: "image/webp", jpg: "image/jpeg", png: "image/png" };

const symbols = PHOTOS.map(([name, file, w, h]) => {
	const bytes = readFileSync(join(here, "img", file));
	const type = MIME[file.split(".").pop()];
	return (
		`<symbol id="ph-${name}" viewBox="0 0 ${w} ${h}">` +
		`<image width="${w}" height="${h}" href="data:${type};base64,${bytes.toString("base64")}"/></symbol>`
	);
});

const out = `<!--
  GENERATED by make-photo-parts.mjs from the files in img/ — do not edit by hand.
-->
<svg id="photo-parts" width="0" height="0" aria-hidden="true" focusable="false"
     style="position:absolute;width:0;height:0;overflow:hidden;pointer-events:none">
${symbols.join("\n")}
</svg>
`;
writeFileSync(join(here, "photo-parts.include.html"), out);
console.log(`photo-parts: ${PHOTOS.length} photographs, ${(out.length / 1024).toFixed(0)} KB`);
